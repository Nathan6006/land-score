"""Write docs/RESULTS.md. Rule 3: county-holdout numbers sit next to every accuracy claim.
Rule 4: if the main models do not beat the baselines, the text says so plainly."""

from __future__ import annotations

from datetime import date
from pathlib import Path

import pandas as pd

from landscore.config import load_config


def _table(res: pd.DataFrame, task: str, metrics: list[str]) -> str:
    r = res[res.task == task]
    schemes = [s for s in ("county", "block", "random") if s in set(r.scheme)]
    header = "| model | " + " | ".join(f"{m} ({s})" for s in schemes for m in metrics) + " |"
    sep = "|---" * (1 + len(schemes) * len(metrics)) + "|"
    lines = [header, sep]
    for model in r["model"].unique():
        cells = []
        for s in schemes:
            row = r[(r.model == model) & (r.scheme == s)].iloc[0]
            cells += [f"{row[m]:.3f}" for m in metrics]
        lines.append(f"| {model} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def verdict(res: pd.DataFrame, headline: str) -> str:
    r = res[(res.task == "binary") & (res.scheme == headline)].set_index("model")
    base = r[r.kind == "baseline"]["auc"]
    main = r[r.kind == "main"]["auc"]
    best_base, best_main = base.idxmax(), main.idxmax()
    gap = main.max() - base.max()
    if gap <= 0.01:
        return (
            f"**The main models do not meaningfully beat the simple baselines** under {headline} "
            f"holdout: best main model {best_main} AUC {main.max():.3f} vs best baseline "
            f"{best_base} AUC {base.max():.3f} (difference {gap:+.3f}). Treat the score as no "
            "better than the baseline until this changes."
        )
    return (
        f"Under {headline} holdout the best main model ({best_main}, AUC {main.max():.3f}) beats "
        f"the best baseline ({best_base}, AUC {base.max():.3f}) by {gap:+.3f} AUC."
    )


def write_results(df, res, headline, best, figs, path: Path) -> None:
    cfg = load_config()
    lab = cfg["labels"]
    counties = ", ".join(sorted(df["county"].unique()))
    scheme_note = (
        "**county** = leave one county out (headline)."
        if headline == "county"
        else "**No county holdout yet: only one county is built.** The headline here is "
        "**block** (5 km spatial blocks), which is weaker evidence than county holdout. "
        "Do not quote these numbers as county-holdout results."
    )
    text = f"""# Results

Generated by `uv run landscore train` on {date.today().isoformat()}. Do not edit by hand;
rerun the command. Counties: {counties}. Labeled pixels: {len(df):,}
(positive rate {df["label_binary"].mean():.1%}).

Target: canopy cover >= {lab["binary_threshold"]}% measured {lab["outcome_lag"]} years after a
field stopped being farmed (abandonment {lab["abandon_window"][0]}-{lab["abandon_window"][1]}).
This is a stand-in for planting success. It measures site potential for natural regrowth,
not survival of planted trees.

Validation: {scheme_note} **block** = 5 km spatial blocks. **random** = random 5-fold
(optimistic, shown for contrast).

## Verdict

{verdict(res, headline)}

## Binary target (canopy >= {lab["binary_threshold"]}%)

{_table(res, "binary", ["auc", "brier_skill"])}

AUC: 0.5 = chance, 1 = perfect ranking. Brier skill: 0 = no better than always predicting the
base rate, 1 = perfect.

![model comparison]({figs.get("comparison", "")})

## Regression target (canopy percent)

{_table(res, "regression", ["r2", "spearman"])}

## Calibration ({headline} holdout)

![calibration]({figs.get("calibration", "")})

## Feature importance (SHAP, {best}, fit on all data)

{f"![shap]({figs['shap']})" if "shap" in figs else "SHAP not computed in this run."}

## Human checks (not done yet)

1. **Forester blind ranking.** A forester ranks ~20 plots without seeing scores; we report the
   rank correlation with the model. *Result: pending.*
2. **Roots planting sites.** Case studies of Roots of Tomorrow's own sites compared with
   observed survival notes. *Result: pending.*

## Lidar check

See the lidar section of `docs/METHODS.md` when available. *Result: pending.*
"""
    path.write_text(text, encoding="utf-8")
